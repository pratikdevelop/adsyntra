
import { Router } from "express";
import type { Request, Response, NextFunction } from "express";
import { getAuth } from "@clerk/express";

import {
    generateCreativeVariations,
} from "../services/ai-creative.service.js";

import type {
    GenerateCreativeBody,
    GenerateCreativeResponse,
} from "../types/ai-creative.types.js";

/* -------------------------------------------------------------------------- */
/* Authentication                                                             */
/* -------------------------------------------------------------------------- */

export function getAuthenticatedUserId(req: Request): string | null {
    const auth = getAuth(req);

    if (!auth.isAuthenticated || !auth.userId) {
        return null;
    }

    return auth.userId;
}

/* -------------------------------------------------------------------------- */
/* Request validation                                                         */
/* -------------------------------------------------------------------------- */

function isRecord(value: unknown): value is Record<string, unknown> {
    return (
        typeof value === "object" &&
        value !== null &&
        !Array.isArray(value)
    );
}

function validateRequestBody(
    value: unknown,
): GenerateCreativeBody | string {
    if (!isRecord(value)) {
        return "Request body must be a valid JSON object.";
    }

    if (
        typeof value.prompt !== "string" ||
        !value.prompt.trim()
    ) {
        return "Request body must include a valid prompt string.";
    }

    const prompt = value.prompt.trim();

    if (prompt.length < 8) {
        return "Creative prompt must be at least 8 characters long.";
    }

    if (prompt.length > 2000) {
        return "Creative prompt must not exceed 2000 characters.";
    }

    if (
        value.numberOfVariations !== undefined &&
        ![1, 2, 3].some(
            (count) => count === value.numberOfVariations,
        )
    ) {
        return "numberOfVariations must be 1, 2, or 3.";
    }

    return value as unknown as GenerateCreativeBody;
}

/* -------------------------------------------------------------------------- */
/* Error classification                                                       */
/* -------------------------------------------------------------------------- */

type CreativeErrorCategory =
    | "VALIDATION"
    | "CONFIGURATION"
    | "PROVIDER"
    | "INTERNAL";

interface ClassifiedCreativeError {
    category: CreativeErrorCategory;
    statusCode: number;
    code: string;
    message: string;
}

function classifyCreativeError(
    error: unknown,
): ClassifiedCreativeError {
    const message =
        error instanceof Error
            ? error.message
            : "An unexpected creative generation error occurred.";

    // Configuration errors originate from the backend environment.
    // They should never be reported as client-side validation errors.
    if (
        /GROQ_API_KEY is not configured/i.test(message) ||
        /POLLINATIONS_API_KEY is missing/i.test(message) ||
        /Unsupported IMAGE_PROVIDER/i.test(message)
    ) {
        return {
            category: "CONFIGURATION",
            statusCode: 503,
            code: "AI_CREATIVE_CONFIGURATION_ERROR",
            message,
        };
    }

    // These messages are generated by the request validation
    // implemented in the AI Creative service.
    const validationPatterns = [
        /^A valid creative request body is required/i,
        /^Creative prompt must/i,
        /^Unsupported creative kind/i,
        /^Video creative generation is not available yet/i,
        /^Unsupported creative aspect ratio/i,
        /^Unsupported Google Ads aspect ratio/i,
        /^Unsupported Google Ads campaign type/i,
        /^Unsupported Google Demand Gen format/i,
        /^numberOfVariations must/i,
        /^Creative style must/i,
        /^Platforms must/i,
        /^One or more selected platforms/i,
        /^Brand website URL must/i,
        /^Only HTTP and HTTPS URLs/i,

        // Campaign-aware validation
        /^creativeTargets must/i,
        /^assetRequests must/i,
        /^One or more creative targets are invalid/i,
        /^Unsupported AI creative capability/i,
        /^Creative target .* does not match/i,
        /^Select .* in platforms/i,
        /^Duplicate creative target/i,
        /^Invalid provider objective/i,
        /^A generation request can contain at most/i,
        /^creativeTargets are required/i,
        /^Image asset requests cannot/i,
        /^One or more asset generation requests are invalid/i,
        /^Asset request .* references a capability/i,
        /^Unsupported asset requirement/i,
        /^Only IMAGE asset generation/i,
        /^Unsupported asset aspect ratio/i,
        /does not support aspect ratio/i,
        /requires between/i,
        /^Duplicate asset request/i,
        /^A single generation request can generate at most/i,
        /requires an asset request for/i,
        /^textOnly must/i,
        /^Supply a business name before generating an AI logo concept/i,
    ];

    if (validationPatterns.some((pattern) => pattern.test(message))) {
        return {
            category: "VALIDATION",
            statusCode: 400,
            code: "AI_CREATIVE_VALIDATION_ERROR",
            message,
        };
    }

    // Provider failures are upstream service failures.
    if (
        /Groq copy generation failed/i.test(message) ||
        /Pollinations image generation failed/i.test(message) ||
        /^AI creative generation failed/i.test(message)
    ) {
        return {
            category: "PROVIDER",
            statusCode: 502,
            code: "AI_CREATIVE_PROVIDER_ERROR",
            message,
        };
    }

    return {
        category: "INTERNAL",
        statusCode: 500,
        code: "AI_CREATIVE_INTERNAL_ERROR",
        message: "An unexpected error occurred while generating creatives.",
    };
}

/* -------------------------------------------------------------------------- */
/* Error response                                                             */
/* -------------------------------------------------------------------------- */

function sendCreativeError(
    res: Response,
    error: unknown,
): void {
    const classified = classifyCreativeError(error);

    // Log the failure without exposing API credentials or request prompts.
    console.error("[AI Creative] Generation failed:", {
        category: classified.category,
        code: classified.code,
        message:
            error instanceof Error
                ? error.message
                : String(error),
    });

    res.status(classified.statusCode).json({
        success: false,
        code: classified.code,
        message: classified.message,
    });
}


function hasValidGeneratedAssets(
    assets: unknown,
): boolean {
    if (!Array.isArray(assets)) {
        return false;
    }

    return assets.every((asset) => {
        if (!isRecord(asset)) {
            return false;
        }

        if (!isRecord(asset.media)) {
            return false;
        }

        return (
            typeof asset.id === "string" &&
            typeof asset.generationId === "string" &&
            typeof asset.capabilityId === "string" &&
            typeof asset.requirementId === "string" &&
            typeof asset.role === "string" &&
            typeof asset.assetIndex === "number" &&
            typeof asset.name === "string" &&
            typeof asset.media.url === "string"
        );
    });
}

function hasValidCapabilityCopies(
    copies: unknown,
): boolean {
    if (!Array.isArray(copies)) {
        return false;
    }

    return copies.every((copy) => {
        if (!isRecord(copy) || !Array.isArray(copy.texts)) {
            return false;
        }

        if (
            typeof copy.capabilityId !== "string" ||
            typeof copy.platform !== "string" ||
            typeof copy.campaignType !== "string" ||
            typeof copy.adFormat !== "string"
        ) {
            return false;
        }

        return copy.texts.every((item: unknown) => {
            if (!isRecord(item)) {
                return false;
            }

            // GeneratedCapabilityCopyText is scoped by its parent copy, so
            // capabilityId belongs on `copy`, not on each nested text item.
            return (
                typeof item.requirementId === "string" &&
                typeof item.field === "string" &&
                typeof item.textIndex === "number" &&
                typeof item.text === "string"
            );
        });
    });
}

function hasValidBrandIdentity(
    value: unknown,
): boolean {
    if (!isRecord(value)) {
        return false;
    }

    return (
        typeof value.businessName === "string" &&
        value.businessName.trim().length > 0 &&
        value.source === "USER_INPUT" &&
        (value.websiteUrl === undefined || typeof value.websiteUrl === "string")
    );
}

/* -------------------------------------------------------------------------- */
/* Response validation                                                        */
/* -------------------------------------------------------------------------- */

function hasValidVariations(
    variations: unknown,
): boolean {
    if (!Array.isArray(variations)) {
        return false;
    }

    return variations.every((variation) => {
        if (!isRecord(variation)) {
            return false;
        }

        return (
            typeof variation.id === "string" &&
            typeof variation.name === "string" &&
            typeof variation.kind === "string" &&
            typeof variation.url === "string" &&
            typeof variation.headline === "string" &&
            typeof variation.primaryText === "string"
        );
    });
}

/* -------------------------------------------------------------------------- */
/* Router                                                                     */
/* -------------------------------------------------------------------------- */

const router = Router();

/* -------------------------------------------------------------------------- */
/* POST /api/ai-creative/generate                                             */
/* -------------------------------------------------------------------------- */

router.post(
    "/generate",
    async (
        req: Request,
        res: Response,
        next: NextFunction,
    ): Promise<void> => {
        try {
            /* ---------------------------------------------------------------- */
            /* 1. Authenticate user                                             */
            /* ---------------------------------------------------------------- */

            const userId = getAuthenticatedUserId(req);

            if (!userId) {
                res.status(401).json({
                    success: false,
                    code: "AUTHENTICATION_REQUIRED",
                    message: "Authentication required.",
                });
                return;
            }

            /* ---------------------------------------------------------------- */
            /* 2. Validate request body                                         */
            /* ---------------------------------------------------------------- */

            const validatedBody = validateRequestBody(req.body);

            if (typeof validatedBody === "string") {
                res.status(400).json({
                    success: false,
                    code: "AI_CREATIVE_VALIDATION_ERROR",
                    message: validatedBody,
                });
                return;
            }


            /* ---------------------------------------------------------------- */
            /* 3. Generate creative variations                                  */
            /* ---------------------------------------------------------------- */

            const result = await generateCreativeVariations(
                userId,
                validatedBody,
            );

            /* ---------------------------------------------------------------- */
            /* 4. Validate generation response                                  */
            /* ---------------------------------------------------------------- */

            const validVariations = hasValidVariations(result.variations);

            const validAssets = hasValidGeneratedAssets(
                result.generatedAssets,
            );
            const validCapabilityCopies =
                result.generatedCapabilityCopies === undefined ||
                hasValidCapabilityCopies(result.generatedCapabilityCopies);
            // The service contract explicitly returns null when this workflow
            // has no campaign-aware brand identity. Null is a valid empty state.
            const validBrandIdentity =
                result.brandIdentity === undefined ||
                result.brandIdentity === null ||
                hasValidBrandIdentity(result.brandIdentity);

            const invalidResponseParts: string[] = [];
            if (!validVariations) invalidResponseParts.push("variations");
            if (!validAssets) invalidResponseParts.push("generatedAssets");
            if (!validCapabilityCopies) invalidResponseParts.push("generatedCapabilityCopies");
            if (!validBrandIdentity) invalidResponseParts.push("brandIdentity");

            if (invalidResponseParts.length > 0) {
                throw new Error(
                    `Creative generation completed, but its response failed validation: ${invalidResponseParts.join(", ")}.`,
                );
            }

            // At least one workflow must produce a successful output.
            if (
                result.variations.length === 0 &&
                result.generatedAssets.length === 0 &&
                (result.generatedCapabilityCopies?.length ?? 0) === 0
            ) {
                throw new Error(
                    "Creative generation completed without any generated output.",
                );
            }


            /* -------------------------------------------------------------------------- */
            /* 5. Build response message                                                  */
            /* -------------------------------------------------------------------------- */

            const messageParts: string[] = [];

            // Creative variation results
            if (result.requestedCount > 0) {
                if (result.generatedCount === 0) {
                    messageParts.push(
                        `No creative variations were generated. ` +
                        `${result.failedCount} variation(s) failed.`,
                    );
                } else if (result.partialSuccess && result.failedCount > 0) {
                    messageParts.push(
                        `${result.generatedCount} of ${result.requestedCount} ` +
                        `creative variations generated. ${result.failedCount} failed.`,
                    );
                } else {
                    messageParts.push(
                        `Successfully generated ${result.generatedCount} ` +
                        `creative variation(s).`,
                    );
                }
            }

            // Capability-specific text results
            if ((result.generatedCapabilityCopies?.length ?? 0) > 0) {
                messageParts.push(
                    `Generated capability-specific ad copy for ${result.generatedCapabilityCopies!.length} campaign format(s).`,
                );
            }

            const capabilityCopyFailureCount = result.errors.filter(
                (error) => error.code === "CAPABILITY_COPY_GENERATION_FAILED",
            ).length;

            if (capabilityCopyFailureCount > 0) {
                messageParts.push(
                    `Capability-specific ad copy failed for ${capabilityCopyFailureCount} campaign format(s).`,
                );
            }

            // Campaign asset results
            if (result.requestedAssetCount > 0) {
                if (result.failedAssetCount === 0) {
                    messageParts.push(
                        `Successfully generated all ${result.generatedAssetCount} ` +
                        `requested campaign asset(s).`,
                    );
                } else if (result.generatedAssetCount === 0) {
                    messageParts.push(
                        `No campaign assets were generated. ` +
                        `${result.failedAssetCount} asset(s) failed.`,
                    );
                } else {
                    messageParts.push(
                        `Generated ${result.generatedAssetCount} of ` +
                        `${result.requestedAssetCount} campaign assets. ` +
                        `${result.failedAssetCount} failed.`,
                    );
                }
            }

            let message = messageParts.join(" ");

            if (!message) {
                message = "Creative generation completed.";
            }

            // Check placeholders in both output collections.
            const containsPlaceholder =
                result.variations.some(
                    (variation) => variation.media?.isPlaceholder === true,
                ) ||
                result.generatedAssets.some(
                    (asset) => asset.media?.isPlaceholder === true,
                );

            if (containsPlaceholder) {
                message +=
                    " Development placeholder media is included. " +
                    "Replace it with generated media before saving or publishing.";
            }

            const containsTextOnlyVariation = result.variations.some(
                (variation) => !variation.media && !variation.url,
            );

            if (containsTextOnlyVariation) {
                message +=
                    " Some variations contain advertising copy only, without image media.";
            }
            /* ---------------------------------------------------------------- */
            /* 6. Build API response                                            */
            /* ---------------------------------------------------------------- */

            const payload: GenerateCreativeResponse = {
                success: true,

                generationId: result.generationId,

                variations: result.variations,

                provider: result.provider,
                model: result.model,

                imageProvider: result.imageProvider,

                generatedAt: result.generatedAt,

                expiresAt: result.expiresAt,

                requestedCount: result.requestedCount,
                generatedCount: result.generatedCount,
                failedCount: result.failedCount,

                partialSuccess: result.partialSuccess,

                errors: result.errors,
                // Campaign-aware generated assets
                generatedAssets: result.generatedAssets,

                requestedAssetCount: result.requestedAssetCount,
                generatedAssetCount: result.generatedAssetCount,
                failedAssetCount: result.failedAssetCount,

                assetErrors: result.assetErrors,

                ...(result.generatedCapabilityCopies
                    ? { generatedCapabilityCopies: result.generatedCapabilityCopies }
                    : {}),
                ...(result.brandIdentity
                    ? { brandIdentity: result.brandIdentity }
                    : {}),

                message,
            };

            /* ---------------------------------------------------------------- */
            /* 7. Send success response                                         */
            /* ---------------------------------------------------------------- */

            res.status(200).json(payload);
        } catch (error) {
            const classified = classifyCreativeError(error);

            if (classified.category === "INTERNAL") {
                // Allow the existing global error handler to handle
                // unexpected application errors.
                next(error);
                return;
            }

            sendCreativeError(res, error);
        }
    },
);

/* -------------------------------------------------------------------------- */
/* Export                                                                     */
/* -------------------------------------------------------------------------- */

export default router;
